def main():
    tree = ET.parse(EN_FILE)
    root = tree.getroot()
    missing = []
    for message in root.iter('message'):
        source = message.find('source')
        text = source.text if source is not None else ''
        translation = translations.get(text)
        if translation is None:
            missing.append(text)
        else:
            trans_el = message.find('translation')
            if trans_el is None:
                trans_el = ET.SubElement(message, 'translation')
            trans_el.text = translation
    if missing:
        print('Missing translations:', len(missing))
        for text in missing:
            print(text)
        raise SystemExit(1)
    root.set('language', 'zh_CN')
    tree.write(ZH_FILE, encoding='utf-8', xml_declaration=True)
    text = ZH_FILE.read_text(encoding='utf-8')
    if '<!DOCTYPE TS>' not in text:
        text = text.replace('<TS ', '<!DOCTYPE TS>\n<TS ', 1)
    text = text.replace("<?xml version='1.0' encoding='utf-8'?>",
                        "<?xml version=\"1.0\" encoding=\"utf-8\"?>", 1)
    ZH_FILE.write_text(text, encoding='utf-8')

if __name__ == '__main__':
    main()
